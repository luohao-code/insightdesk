"""生成用于演示与测试的示例图片。

用法::

    python scripts/generate_sample.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

BASE_DIR = Path(__file__).resolve().parent.parent
TARGET = BASE_DIR / "docs" / "assets" / "sample-ocr.png"


def load_font(size: int):
    candidates = [
        Path("C:/Windows/Fonts/msyh.ttc"),
        Path("C:/Windows/Fonts/simhei.ttf"),
        Path("/System/Library/Fonts/PingFang.ttc"),
        Path("/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc"),
    ]
    for path in candidates:
        if path.exists():
            try:
                return ImageFont.truetype(str(path), size)
            except OSError:
                continue
    return ImageFont.load_default(size=size)


def main() -> Path:
    width, height = 1080, 620
    image = Image.new("RGB", (width, height), "#ffffff")
    draw = ImageDraw.Draw(image)

    draw.rectangle([(0, 0), (width, 12)], fill="#4f46e5")
    draw.text((64, 62), "识文台 InsightDesk", fill="#0f172a", font=load_font(52))
    draw.text((64, 138), "OCR + AI 智能文字工作台", fill="#334155", font=load_font(34))
    draw.line([(64, 200), (1016, 200)], fill="#cbd5e1", width=2)

    lines = [
        "软件工程课程综合实践 2 · 软件开发实践",
        "支持中英文印刷体识别、批量任务与失败重试",
        "AI 翻译 · 摘要 · 关键词 · 问答",
        "Web extraction · Auto open · History · Export",
        "Batch OCR with concurrency control and retries.",
    ]
    y = 240
    for line in lines:
        draw.text((64, y), line, fill="#1e293b", font=load_font(28))
        y += 58

    draw.rounded_rectangle([(64, 540), (1016, 588)], radius=12, fill="#eef2ff")
    draw.text((84, 551), "Demo image generated by scripts/generate_sample.py", fill="#4f46e5", font=load_font(20))

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    image.save(TARGET, format="PNG", optimize=True)
    print(f"saved: {TARGET}")
    return TARGET


if __name__ == "__main__":
    main()
