"""演示 OCR 引擎。

作用：在没有配置任何云端密钥、也没有安装本地 OCR 组件时，
仍然可以完整体验"上传 → 识别 → 编辑 → AI → 导出 → 历史"全流程。

实现要点：
* 结果由文件名与图片大小确定，同一图片多次识别结果一致；
* 明确标记 ``demo=True``，界面会提示"演示引擎"；
* 不读取图片内容，避免误以为识别真实完成。
"""

from __future__ import annotations

import hashlib
import random
import time
from pathlib import Path

from ..base import OCRProvider, OCRResult, TextBlock

_CORPUS_ZH = [
    "软件需求规格说明书",
    "1 引言",
    "本文档定义识文台系统的功能需求、非功能需求与验收标准。",
    "系统采用浏览器/服务器架构，前端通过 REST 接口与后端通信。",
    "识别结果支持在线编辑、复制、导出与历史检索。",
    "批量任务默认并发数为 3，失败任务会自动重试两次。",
    "所有密钥仅保存在服务端，不会写入前端代码或打包产物。",
    "网页提取模块具备 SSRF 防护，禁止访问内网地址。",
    "用户可以在设置页切换 OCR 引擎与 AI 模型。",
    "系统使用 SQLite 存储文字资产，并启用 WAL 模式提升并发能力。",
    "阶段验收标准：100 张图片批量执行不崩溃，失败项可单独重试。",
    "本段文字由演示引擎生成，仅用于界面与流程演示。",
]

_CORPUS_EN = [
    "InsightDesk OCR Workbench",
    "Software Requirements Specification",
    "The system adopts a layered architecture with a RESTful backend.",
    "Recognized text can be edited, copied, exported and searched.",
    "Batch jobs run with a configurable concurrency limit.",
    "API keys are stored on the server side and never exposed to the browser.",
    "Web extraction validates URLs to prevent SSRF attacks.",
    "All external requests have explicit timeouts and retry policies.",
    "This sample text is generated by the demo engine for demonstration only.",
    "Quality attribute: 100 images should be processed without crashes.",
    "Export formats include TXT, CSV, Markdown, Word and Excel.",
    "Contact: insightdesk@example.com",
]


class MockOCRProvider(OCRProvider):
    name = "mock"
    label = "演示引擎（无需密钥）"
    description = "内置演示引擎，用于在没有 OCR 凭据时体验完整流程，结果为模拟文本。"
    requires_credentials = False
    supports_language = ("auto", "zh", "en")

    def available(self, settings: dict) -> tuple[bool, str]:
        return True, "内置引擎，始终可用"

    def recognize(self, image_path: Path, settings: dict, options: dict | None = None) -> OCRResult:
        started = time.perf_counter()
        options = options or {}
        seed_source = f"{image_path.name}:{image_path.stat().st_size if image_path.exists() else 0}"
        seed = int(hashlib.sha1(seed_source.encode("utf-8")).hexdigest()[:8], 16)
        rng = random.Random(seed)

        language = options.get("language") or settings.get("ocr_language") or "auto"
        if language == "en":
            lines = rng.sample(_CORPUS_EN, k=8)
        elif language == "zh":
            lines = rng.sample(_CORPUS_ZH, k=8)
        else:
            zh_lines = rng.sample(_CORPUS_ZH, k=5)
            en_lines = rng.sample(_CORPUS_EN, k=4)
            lines = zh_lines[:3] + en_lines[:2] + zh_lines[3:] + en_lines[2:]

        # 模拟一点识别噪声，让界面更接近真实结果
        blocks = []
        for index, line in enumerate(lines):
            confidence = round(rng.uniform(0.86, 0.99), 3)
            top = 40 + index * 52
            blocks.append(
                TextBlock(
                    text=line,
                    confidence=confidence,
                    box=[[32.0, float(top)], [880.0, float(top)], [880.0, float(top + 34)], [32.0, float(top + 34)]],
                )
            )

        text = "\n".join(block.text for block in blocks)
        duration = (time.perf_counter() - started) * 1000
        return OCRResult(
            text=text,
            blocks=blocks,
            engine=self.name,
            confidence=round(sum(b.confidence or 0 for b in blocks) / max(1, len(blocks)), 3),
            duration_ms=round(duration + rng.uniform(80, 240), 1),
            meta={
                "demo": True,
                "notice": "当前使用演示引擎，文本为模拟结果。配置云端密钥或安装 RapidOCR 后可获得真实识别结果。",
                "language": language,
            },
        )


provider = MockOCRProvider()
